export const crearExpediente = ({ tipoPaciente, ...datos }) => {
  const nombre = [datos.nombres, datos.primerApellido, datos.segundoApellido]
    .filter(Boolean)
    .join(" ");
  const cuenta = datos.numeroCuenta || datos.numeroIdentidad;
  return {
    ...camposVacios,
    ...datos,
    cuenta,
    nombre,
    tipo: tipoPaciente,
    visita: "Primera vez",
  };
};

